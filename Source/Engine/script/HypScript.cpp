struct HypScriptImpl
{
    CompilationUnit globalCompilationUnit;
    VirtualMachine* vm;
    ScriptInstance* globalInstance;

    HypScriptImpl()
        : vm(new VirtualMachine()),
          globalInstance(nullptr)
    {
    }

    HypScriptImpl(const HypScriptImpl& other) = delete;
    HypScriptImpl& operator=(const HypScriptImpl& other) = delete;

    ~HypScriptImpl()
    {
        if (globalInstance)
        {
            delete globalInstance;
            globalInstance = nullptr;
        }

        delete vm;
    }
};

#pragma endregion HypScriptImpl

/// Initialize the `Lib` script which is used to call into HypScript code from C++.
static Result InitializeHypScriptLib(HypScript& hs)
{
    // create the global script instance using Lib.hyp (generated by the CodeGen tool)
    static const FilePath s_libPath = CoreApi::GetExecutablePath() / "Lib.hyp";

    FileBufferedReaderSource source { s_libPath };
    BufferedByteReader reader { &source };

    if (!reader.IsOpen())
    {
        return HYP_MAKE_ERROR(Error, "Failed to open Lib.hyp at path '{}'! Did the build tool run correctly?", s_libPath);
    }

    ByteBuffer byteBuffer = reader.ReadBytes();

    SourceFile sourceFile(s_libPath, byteBuffer.Size());
    sourceFile.ReadIntoBuffer(byteBuffer);

    ErrorList errorList;

    ScriptInstance* instance = hs.Compile(sourceFile, errorList);

    if (errorList.HasFatalErrors())
    {
        return HYP_MAKE_ERROR(Error, "Failed to compile Lib.hyp! The script system will not function correctly.");
    }

    Assert(instance != nullptr);

    // run the main script to initialize classes, functions, etc.
    hs.Run(instance);

    return {};
}

